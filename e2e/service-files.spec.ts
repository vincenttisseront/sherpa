    // Glisser-déposer : fichiers du poste déposés dans le dossier puis sur un sous-dossier ; ligne glissée sur un dossier = déplacement.
    const files = (list: [string, string][]) => page.evaluateHandle(`(() => { const d = new DataTransfer(); for (const [n, c] of ${JSON.stringify(list)}) d.items.add(new File([c], n)); return d })()`)
    const zone = dialog.getByRole('region', { name: 'Contenu du dossier' })
    const two = await files([['dd1.txt', 'un'], ['dd2.txt', 'deux']])
    await zone.dispatchEvent('dragover', { dataTransfer: two })
    await zone.dispatchEvent('drop', { dataTransfer: two })
    await expect(page.getByText('2 fichiers envoyés dans /config')).toBeVisible({ timeout: 60_000 })
    expect(docker('exec', ctn, 'cat', '/config/dd2.txt')).toBe('deux')
    const pluginsRow = dialog.locator('tr', { has: page.getByRole('link', { name: 'plugins/', exact: true }) })
    const one = await files([['dd3.txt', 'trois']])
    await pluginsRow.dispatchEvent('dragover', { dataTransfer: one })
    await pluginsRow.dispatchEvent('drop', { dataTransfer: one })
    await expect(page.getByText('/config/plugins/dd3.txt envoyé')).toBeVisible({ timeout: 60_000 })
    await dialog.locator('tr', { has: page.getByRole('link', { name: 'dd1.txt', exact: true }) }).dragTo(pluginsRow)
    await expect(page.getByText('/config/dd1.txt déplacé vers /config/plugins/dd1.txt')).toBeVisible({ timeout: 60_000 })
    expect(docker('exec', ctn, 'cat', '/config/plugins/dd1.txt')).toBe('un')
    expect(docker('exec', ctn, 'sh', '-c', 'ls /config/dd1.txt 2>/dev/null || echo absent')).toBe('absent')

    // Renommage en ligne : double-clic (nom sélectionné sans l'extension, la saisie le remplace), F2, Échap.
    await dialog.getByRole('link', { name: 'dd2.txt', exact: true }).dblclick()
    const field = dialog.getByRole('textbox', { name: 'Nouveau nom de dd2.txt' })
    await expect(field).toBeFocused()
    await page.keyboard.type('renomme')
    await page.keyboard.press('Enter')
    await expect(page.getByText('/config/dd2.txt renommé en renomme.txt')).toBeVisible({ timeout: 30_000 })
    expect(docker('exec', ctn, 'cat', '/config/renomme.txt')).toBe('deux')
    await dialog.getByRole('link', { name: 'renomme.txt', exact: true }).focus()
    await page.keyboard.press('F2')
    await expect(dialog.getByRole('textbox', { name: 'Nouveau nom de renomme.txt' })).toBeFocused()
    await page.keyboard.press('Escape')
    await expect(dialog.getByRole('textbox', { name: 'Nouveau nom de renomme.txt' })).toHaveCount(0)
    await expect(dialog.getByRole('link', { name: 'renomme.txt', exact: true })).toBeVisible()

    // Tri des colonnes : dossiers en tête, noms en ordre naturel, taille et date, ordre inversé, choix retenu.
    docker('exec', ctn, 'sh', '-c', 'mkdir -p /config/tri/zz && cd /config/tri && head -c 1000 /dev/zero > b-10.txt && head -c 3 /dev/zero > b-2.txt && head -c 10 /dev/zero > a.txt && touch -d "2026-01-01 10:00:00" b-10.txt && touch -d "2026-03-01 10:00:00" a.txt && touch -d "2026-06-01 10:00:00" b-2.txt')
    await dialog.getByRole('button', { name: 'Relire le dossier' }).click()
    await openDir('tri')
    const order = () => dialog.locator('tbody tr td:nth-child(2) .entry .mono').allInnerTexts()
    const head = (n: string) => dialog.getByRole('columnheader', { name: n })
    await expect.poll(order).toEqual(['zz/', 'a.txt', 'b-2.txt', 'b-10.txt'])
    await expect(head('Nom')).toHaveAttribute('aria-sort', 'ascending')
    await head('Nom').getByRole('button').click()
    await expect.poll(order).toEqual(['zz/', 'b-10.txt', 'b-2.txt', 'a.txt'])
    await head('Taille').getByRole('button').click()
    await expect(head('Taille')).toHaveAttribute('aria-sort', 'descending')
    await expect.poll(order).toEqual(['zz/', 'b-10.txt', 'a.txt', 'b-2.txt'])
    await head('Modifié').getByRole('button').click()
    await expect.poll(order).toEqual(['zz/', 'b-2.txt', 'a.txt', 'b-10.txt'])
    await head('Modifié').getByRole('button').click()
    await expect.poll(order).toEqual(['zz/', 'b-10.txt', 'a.txt', 'b-2.txt'])
    expect(await page.evaluate('localStorage.getItem("service-files.sort")')).toBe('{"key":"mtime","dir":"asc"}')
    await head('Nom').getByRole('button').click()
    await openRoot()

    // Filtre rapide : « / » y place le curseur, filtre sans casse, compteur, « Tout sélectionner » sur l'affiché, Échap le vide.
    const total = await dialog.locator('tbody tr td:nth-child(2) .entry .mono').count()
    await dialog.getByRole('columnheader', { name: 'Taille' }).click()
    await page.keyboard.press('/')
    const quick = dialog.getByRole('searchbox', { name: 'Filtrer ce dossier par nom' })
    await expect(quick).toBeFocused()
    await page.keyboard.type('PACK')
    const shown = await dialog.locator('tbody tr td:nth-child(2) .entry .mono').allInnerTexts()
    expect(shown.length).toBeGreaterThan(1)
    expect(shown.every(n => n.toLowerCase().includes('pack'))).toBe(true)
    await expect(dialog.getByText(`${shown.length} sur ${total}`)).toBeVisible()
    await dialog.getByRole('checkbox', { name: 'Tout sélectionner' }).check()
    await expect(dialog.getByRole('toolbar', { name: 'Sélection' }).getByText(`${shown.length} sélectionnés`)).toBeVisible()
    await dialog.getByRole('toolbar', { name: 'Sélection' }).getByRole('button', { name: 'Désélectionner' }).click()
    await quick.fill('introuvable-xyz')
    await expect(dialog.getByText('Aucun élément ne correspond à « introuvable-xyz ».')).toBeVisible()
    await quick.press('Escape')
    await expect(quick).toHaveValue('')
    await expect(dialog).toBeVisible()
    await expect(dialog.locator('tbody tr td:nth-child(2) .entry .mono')).toHaveCount(total)

    // Navigation au clavier : flèches, saisie de lettres, Entrée (dossier, fichier), Retour arrière, Espace, Ctrl+A, Échap, F2.
    const grid = dialog.getByRole('grid', { name: /Contenu du dossier/ })
    const activeName = async () => {
      const id = await grid.getAttribute('aria-activedescendant')
      return id ? (await dialog.locator(`[id="${id}"] td:nth-child(2) .entry .mono`).innerText()) : null
    }
    await grid.focus()
    await page.keyboard.press('Home')
    const firstName = await activeName()
    await page.keyboard.press('ArrowDown')
    expect(await activeName()).not.toBe(firstName)
    await page.keyboard.type('tr')
    await expect.poll(activeName).toBe('tri/')
    await page.keyboard.press('Enter')
    await expect(dialog.getByRole('navigation', { name: 'Chemin' }).getByRole('link', { name: 'tri', exact: true })).toBeVisible()
    await expect(grid).toBeFocused()
    await page.keyboard.press('Backspace')
    await expect(dialog.getByRole('navigation', { name: 'Chemin' }).getByRole('link')).toHaveCount(1)
    await grid.focus()
    await page.keyboard.type('core')
    await expect.poll(activeName).toBe('core.conf')
    await page.keyboard.press(' ')
    await expect(dialog.getByRole('toolbar', { name: 'Sélection' }).getByText('1 sélectionné')).toBeVisible()
    await page.keyboard.press('ControlOrMeta+a')
    await expect(dialog.getByRole('toolbar', { name: 'Sélection' }).getByText(`${total} sélectionnés`)).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(dialog.getByRole('toolbar', { name: 'Sélection' })).toHaveCount(0)
    await expect(dialog).toBeVisible()
    await page.keyboard.press('F2')
