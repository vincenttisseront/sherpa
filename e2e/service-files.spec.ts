    await openDir('plugins')
    await dialog.getByRole('button', { name: 'Copier ici' }).click()
    await expect(page.getByText('2 éléments copiés vers /config/plugins')).toBeVisible({ timeout: 60_000 })
    expect(docker('exec', ctn, 'cat', '/config/plugins/m2.txt')).toBe('deux')
    await openRoot()
    for (const n of ['m1.txt', 'm2.txt', 'mdir']) await dialog.getByRole('checkbox', { name: `Sélectionner ${n}`, exact: true }).check()
    await bulk.getByRole('button', { name: 'Supprimer' }).click()
    const del = page.getByRole('dialog', { name: 'Supprimer 3 élément(s)' })
    await del.getByLabel(/Saisir/).fill('supprimer')
    await del.getByRole('button', { name: 'Supprimer' }).click()
    await expect(page.getByText('3 élément(s) supprimé(s)')).toBeVisible({ timeout: 60_000 })
    expect(docker('exec', ctn, 'ls', '/config')).not.toMatch(/^(m1\.txt|m2\.txt|mdir)$/m)
    await dialog.getByRole('checkbox', { name: 'Tout sélectionner' }).check()
    await expect(bulk.getByText(new RegExp(`^${await dialog.getByRole('checkbox', { name: /^Sélectionner / }).count()} sélectionnés$`))).toBeVisible()
