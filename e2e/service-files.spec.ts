    expect(docker('exec', ctn, 'sh', '-c', 'ls /config/b-2.txt /config/tri/ajout.conf')).toContain('/config/tri/ajout.conf')
    await grid.focus()
    await page.evaluate(`(() => { const d = new DataTransfer(); d.items.add(new File(['colle'], 'colle.txt')); document.activeElement.dispatchEvent(new ClipboardEvent('paste', { clipboardData: d, bubbles: true, cancelable: true })) })()`)
