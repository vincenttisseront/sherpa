    await expect(dialog).toBeVisible()
    await dialog.getByRole('region', { name: 'Contenu du dossier' }).locator('.drop-hint, .quick').first().click({ button: 'right', force: true })
    const folderCtx = dialog.getByRole('menu', { name: 'Actions : /config' })
